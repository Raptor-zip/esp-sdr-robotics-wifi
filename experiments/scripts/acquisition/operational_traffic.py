class PacedTraffic(Traffic):
 def __init__(self,local):
  super().__init__(local);self.rate_mbps=0.;self.period_ms=100.;self.generation=0;self.connection_generation=-1
 def configure(self,run_id,level='off',seconds=0,requested_mbps=None,period_ms=100):
  rate={'off':0.,'medium':7.86432,'heavy':15.72864}[level] if requested_mbps is None else float(requested_mbps)
  if not math.isfinite(rate) or not 0<=rate<=20:raise ValueError('rate outside 0..20 Mbps')
  period=float(period_ms)
  if not math.isfinite(period) or not 1<=period<=1000:raise ValueError('period outside 1..1000 ms')
  seconds=float(seconds)
  if not math.isfinite(seconds) or not 0<=seconds<=1800:raise ValueError('duration outside 0..1800 seconds')
  with self.lock:
   self.run_id=int(run_id);self.level=level;self.rate_mbps=rate;self.period_ms=period;self.start=time.monotonic();self.until=self.start+seconds;self.bytes=0;self.frames=0;self.generation+=1
  return self.snapshot()
 @staticmethod
 def generated_bytes(elapsed,rate,period_ms):
  ticks=max(0,math.floor(elapsed/(period_ms/1000))+1)
  return math.floor(ticks*rate*1e6/8*(period_ms/1000))
 def snapshot(self):
  with self.lock:
   now=time.monotonic();generated=self.generated_bytes(max(0,min(now,self.until)-self.start),self.rate_mbps,self.period_ms) if self.start and self.rate_mbps else 0
   return dict(helper_version=2,configuration_generation=self.generation,tcp_connection_generation=self.connection_generation,run_id=self.run_id,level=self.level,requested_mbps=self.rate_mbps,period_ms=self.period_ms,sent_payload_bytes=[self.bytes,0],generated_payload_bytes=generated,pending_application_bytes=max(0,generated-self.bytes),sent_messages=[self.frames,0],tcp_connected=self.connected,echoes=self.echoes,monotonic_ns=time.monotonic_ns(),wall_ns=time.time_ns(),semantics='Synthetic TCP byte stream with periodic byte generation; pending generated bytes accumulate under backpressure; new TCP connection per configuration; not ROS 2 or real video')
 def sender(self):
  listener=socket.socket();listener.setsockopt(socket.SOL_SOCKET,socket.SO_REUSEADDR,1);listener.bind((self.local,5003));listener.listen(2);listener.settimeout(.3);payload=bytes([0x5a])*8192
  while not self.stop.is_set():
   try:s,_=listener.accept()
   except socket.timeout:continue
   s.setblocking(False);s.setsockopt(socket.SOL_SOCKET,socket.SO_KEEPALIVE,1);s.setsockopt(socket.IPPROTO_TCP,socket.TCP_KEEPIDLE,2);s.setsockopt(socket.IPPROTO_TCP,socket.TCP_KEEPINTVL,1);s.setsockopt(socket.IPPROTO_TCP,socket.TCP_KEEPCNT,3);s.setsockopt(socket.IPPROTO_TCP,socket.TCP_NODELAY,1);s.setsockopt(socket.SOL_SOCKET,socket.SO_SNDBUF,32768);self.connected=True
   with self.lock:connection_generation=self.generation;self.connection_generation=connection_generation
   try:
    while not self.stop.is_set():
     with self.lock:changed=self.generation!=connection_generation
     if changed:
      # Discard queued payload from the previous requested rate, rather than
      # allowing it to spill into the next benchmark window.
      s.setsockopt(socket.SOL_SOCKET,socket.SO_LINGER,struct.pack('ii',1,0));break
     if select.select([s],[],[],0)[0] and not s.recv(1,socket.MSG_PEEK):break
     with self.lock:
      now=time.monotonic();active=now<self.until and self.rate_mbps>0
      budget=max(0,self.generated_bytes(now-self.start,self.rate_mbps,self.period_ms)-self.bytes) if active else 0
      generation=self.generation
     if not budget:self.stop.wait(.0005);continue
     if not select.select([], [s], [], .005)[1]:continue
     try:n=s.send(payload[:min(budget,len(payload))])
     except BlockingIOError:continue
     with self.lock:
      if generation==self.generation:self.bytes+=n;self.frames=self.bytes//max(1,int(self.rate_mbps*1e6/8*self.period_ms/1000))
   except OSError:pass
   finally:self.connected=False;s.close()
  listener.close()

